def check(ok, kind, what, detail=""):
    global bad, skipped
    if not ok and not HAVE_RUN and f"{kind.strip()} {what}".rstrip() in _NEEDS:
        print(f"SKIP {kind:9}", what, "(needs run_python, which is off on this platform)")
        skipped += 1
        return
    print(("PASS " if ok else "FAIL ") + f"{kind:9}", what, ("-> " + detail) if detail else "")
    bad += not ok



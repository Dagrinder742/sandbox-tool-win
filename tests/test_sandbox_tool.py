# Layer 1, any OS with /proc: the WHOLE job path runs for real, with a stand-in for the five _WinJob methods
# (all Win32 calls live in _WinJob). Layer 2, Windows only: the same scenarios with the REAL _WinJob.
class _FakeJob:
    made, fail_create, fail_assign, next_peak, seen_marker = [], False, False, None, None

    def __init__(self, mem_mb, cpu_s):
        if _FakeJob.fail_create:
            raise OSError("fake: CreateJobObjectW failed")
        self.mem_mb, self.cpu_s, self.proc, self.closed, self.terminated = mem_mb, cpu_s, None, False, None
        _FakeJob.made.append(self)

    def assign(self, proc):
        if _FakeJob.fail_assign:
            self.proc = proc                    # kept, so the test can see whether the tool killed it
            raise OSError("fake: AssignProcessToJobObject failed")
        time.sleep(0.4)                         # if the child did not wait for "go", its first line would run now
        _FakeJob.seen_marker = (SB / "job_marker.txt").exists()
        self.proc = proc

    def written(self):
        try:
            with open(f"/proc/{self.proc.pid}/io") as f:
                return next(int(l.split()[1]) for l in f if l.startswith("wchar:"))
        except (OSError, StopIteration, ValueError):
            return 0

    def peak_mb(self):
        return _FakeJob.next_peak

    def terminate(self, code):
        self.terminated = code
        self.proc.kill()

    def close(self):
        self.closed = True


